export const MESSAGES = { en, 'zh-CN': zh } as const

export type Locale = keyof typeof MESSAGES
export type MessageKey = keyof typeof en

export const SUPPORTED_LOCALES: Locale[] = ['en', 'zh-CN']

export function translate(
  locale: string,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  const table = (MESSAGES as Record<string, Record<string, string>>)[locale] ?? en
  const template = table[key] ?? en[key] ?? key
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  )
}

/** Task statuses are product vocabulary, not labels; they stay untranslated as data. */
const STATUS_LABELS: Record<string, { en: string; zh: string }> = {
  created: { en: 'queued', zh: '排队中' },
  discussing_request: { en: 'reply pending', zh: '等待回复' },
  extracting: { en: 'reading the source', zh: '正在读取源图' },
  generating_image: { en: 'generating', zh: '正在生成' },
  prompt_ready: { en: 'prompt ready', zh: '提示词就绪' },
  outcome_unknown: { en: 'outcome unknown', zh: '结果未知' },
  failed: { en: 'failed', zh: '失败' },
}

export function statusText(locale: string, status: string): string {
  const entry = STATUS_LABELS[status]
  if (!entry) return status
  return locale === 'zh-CN' ? entry.zh : entry.en
}

const STATUS_TONE: Record<string, 'active' | 'ready' | 'stop'> = {
  created: 'active',
  discussing_request: 'active',
  extracting: 'active',
  generating_image: 'active',
  prompt_ready: 'ready',
  outcome_unknown: 'stop',
  failed: 'stop',
}

export function statusTone(status: string): 'active' | 'ready' | 'stop' | undefined {
  return STATUS_TONE[status]
}

/** Which statuses mean the runtime still has work for this task. */
export const BUSY_STATUSES = new Set([
  'created',
  'discussing_request',
  'extracting',
  'generating_image',
])

