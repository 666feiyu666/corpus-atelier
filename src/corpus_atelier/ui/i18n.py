def translate(language: str, key: str, **values: Any) -> str:
    """Return a localized UI string with a safe fallback to Chinese."""
    catalog = TRANSLATIONS.get(language, TRANSLATIONS[DEFAULT_LANGUAGE])
    template = catalog.get(key, TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key))
    return template.format(**values) if values else template
